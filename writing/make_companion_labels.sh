#!/usr/bin/env bash
# Regenerate companion_labels.tex from the companion paper's .aux file.
#
# arXiv discards uploaded .aux files, so the xr cross-references into the
# companion paper (\ref*{B-...}) would all resolve to "??" there. This script
# embeds the companion's .aux inside a filecontents* block; the forest paper
# \input's it in the preamble so TeX writes the .aux back out at compile time.
#
# Run this AFTER the final compile of schubert_bialgebra_separate_paper.tex,
# then upload companion_labels.tex alongside forest_lr_rule_separate_paper.tex.
set -euo pipefail

cd "$(dirname "$0")"

SRC=schubert_bialgebra_separate_paper.aux
OUT=companion_labels.tex
TARGET=schubert_bialgebra_separate_paper_labels.aux

[ -f "$SRC" ] || { echo "missing $SRC; compile the companion paper first" >&2; exit 1; }

{
  echo "% Generated by make_companion_labels.sh from $SRC on $(date -u +%Y-%m-%dT%H:%MZ). Do not edit."
  echo "\\begin{filecontents*}[overwrite]{$TARGET}"
  cat "$SRC"
  echo "\\end{filecontents*}"
} > "$OUT"

echo "wrote $OUT ($(grep -c '^\\newlabel' "$SRC") labels)"
